#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef struct {
    char name[64];
    char slot[80];
} Slot;

static Slot slots[256];
static int slot_count = 0;
static int temp_count = 0;
static int label_count = 0;
static int block_terminated = 0;

static char* dup_text(const char* text) {
    char* copy = (char*)malloc(strlen(text) + 1);
    if (!copy) exit(2);
    strcpy(copy, text);
    return copy;
}

static char* format_text(const char* prefix, int number) {
    char buffer[64];
    snprintf(buffer, sizeof(buffer), "%s%d", prefix, number);
    return dup_text(buffer);
}

static const char* literal(const char* text) {
    return text;
}

static const char* new_temp(void) {
    return format_text("%t", ++temp_count);
}

static const char* new_value(void) {
    return format_text("%v", ++temp_count);
}

static const char* new_label(const char* prefix) {
    char buffer[64];
    snprintf(buffer, sizeof(buffer), "%s%d", prefix, ++label_count);
    return dup_text(buffer);
}

static int is_immediate(const char* value) {
    int i = 0;
    if (value[0] == '-') i = 1;
    if (value[i] == '\0') return 0;
    for (; value[i] != '\0'; i++) {
        if (value[i] < '0' || value[i] > '9') return 0;
    }
    return 1;
}

static const char* ensure_slot(const char* name) {
    for (int i = 0; i < slot_count; i++) {
        if (strcmp(slots[i].name, name) == 0) return slots[i].slot;
    }
    snprintf(slots[slot_count].name, sizeof(slots[slot_count].name), "%s", name);
    snprintf(slots[slot_count].slot, sizeof(slots[slot_count].slot), "%%%s.addr", name);
    printf("  %s = alloca i32, align 4\n", slots[slot_count].slot);
    return slots[slot_count++].slot;
}

static void declare_variable(const char* name) {
    ensure_slot(name);
}

static const char* value_i32(const char* value) {
    if (is_immediate(value) || value[0] == '%') return value;
    const char* slot = ensure_slot(value);
    const char* loaded = new_value();
    printf("  %s = load i32, ptr %s, align 4\n", loaded, slot);
    return loaded;
}

static const char* emit_load(const char* name) {
    const char* slot = ensure_slot(name);
    const char* loaded = new_value();
    printf("  %s = load i32, ptr %s, align 4\n", loaded, slot);
    return loaded;
}

static void emit_store(const char* name, const char* value) {
    const char* slot = ensure_slot(name);
    printf("  store i32 %s, ptr %s\n", value_i32(value), slot);
    block_terminated = 0;
}

static const char* emit_binary(const char* op, const char* left, const char* right, int compare) {
    const char* result = new_temp();
    if (compare) {
        printf("  %s = icmp %s i32 %s, %s\n", result, op, value_i32(left), value_i32(right));
    } else {
        printf("  %s = %s i32 %s, %s\n", result, op, value_i32(left), value_i32(right));
    }
    block_terminated = 0;
    return result;
}

static const char* emit_call(const char* function_name, int argc, const char** args) {
    const char* result = new_temp();
    printf("  %s = call i32 @%s(", result, function_name);
    for (int i = 0; i < argc; i++) {
        if (i > 0) printf(", ");
        printf("i32 %s", value_i32(args[i]));
    }
    printf(")\n");
    block_terminated = 0;
    return result;
}

static void emit_goto(const char* label) {
    printf("  br label %%%s\n", label);
    block_terminated = 1;
}

static void emit_if_false(const char* condition, const char* false_label) {
    const char* then_label = new_label("bb");
    printf("  br i1 %s, label %%%s, label %%%s\n", condition, then_label, false_label);
    printf("%s:\n", then_label);
    block_terminated = 0;
}

static void emit_label(const char* label) {
    if (!block_terminated) emit_goto(label);
    printf("%s:\n", label);
    block_terminated = 0;
}

static void emit_return(const char* value) {
    printf("  ret i32 %s\n", value_i32(value));
    block_terminated = 1;
}

static void begin_function(const char* name, int argc, const char** params) {
    slot_count = 0;
    temp_count = 0;
    block_terminated = 0;
    printf("define i32 @%s(", name);
    for (int i = 0; i < argc; i++) {
        if (i > 0) printf(", ");
        printf("i32 %%%s", params[i]);
    }
    printf(") {\n");
    printf("entry:\n");
    for (int i = 0; i < argc; i++) {
        const char* slot = ensure_slot(params[i]);
        printf("  store i32 %%%s, ptr %s\n", params[i], slot);
    }
}

static void end_function(void) {
    if (!block_terminated) {
        printf("  ret i32 0\n");
    }
    printf("}\n\n");
}

int main(void) {
    puts("; generated by yysemantic.c");
    puts("");
    begin_function("main", 0, NULL);
    declare_variable("a");
    const char* v1 = literal("1");
    emit_store("a", v1);
    declare_variable("b");
    const char* v2 = literal("2");
    emit_store("b", v2);
    const char* v3 = emit_load("a");
    const char* v4 = emit_load("b");
    const char* v5 = emit_binary("add", v3, v4, 0);
    emit_return(v5);
    end_function();

    return 0;
}
